// mockEmptyFieldSearch serves both the ObjectTypes-filtered lookup SyncFields
// does before syncing defs and the unfiltered deletion scan, finding nothing.
func mockEmptyFieldSearch(api *plugintest.API, groupID string) {
	api.On("SearchPropertyFields", groupID, mock.MatchedBy(func(opts model.PropertyFieldSearchOpts) bool {
		return opts.PerPage > 0 && opts.TargetType == ""
	})).Return([]*model.PropertyField{}, nil)
}

// mockFieldLookup serves only the ObjectTypes-filtered lookup, returning the
// given existing fields. The deletion scan's unfiltered search does not match.
func mockFieldLookup(api *plugintest.API, groupID string, fields ...*model.PropertyField) {
	api.On("SearchPropertyFields", groupID, mock.MatchedBy(func(opts model.PropertyFieldSearchOpts) bool {
		return len(opts.ObjectTypes) == 1 && opts.ObjectTypes[0] == model.PropertyFieldObjectTypeUser
	})).Return(fields, nil)
}

